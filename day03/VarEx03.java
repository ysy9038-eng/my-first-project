class VarEx03{
	public static void main(String[] args){
		// 실수형 float < double(기본)
		
		float f = 3.12F;	// F, f 사용하여 타입을 명확하게 해줌
		double d = 3.14;
		double d2 = 3.12;
		System.out.println(f);
		System.out.println(d);
		System.out.println( f + d );	//6.26
		System.out.println( d + d2);
	}
}
class VarEx02{
	public static void main(String[] args){
		// long 타입 -2의63제곱 ~ 2의63제곱-1
		 
		long var1 = 10;
		long var2 = 20L;	//L 명확하게 long 타입을 표시
		
		long var3 = 1000000000000L; //1조(0이 12개), L / l 사용
		System.out.println( var1 );
		System.out.println( var2 );
		System.out.println( var3 );
	}
}


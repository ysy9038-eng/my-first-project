class ForEx02{
	public static void main(String[] args){
	//for(1초기식; 2조건식; 3증감식; 4실행문)*/
		//1~5까지 반복
		int a;
		for(a= 1; a<=5; a++){
			System.out.println(a);
		}
		System.out.println("====");
		// 1~10 출력
		int b;
		for(b=1; b<11; b++){
			System.out.println(b);
		}
		// 1~100출력
		int c;
		for(c=1; c<=100; c++ ){
			System.out.println(c);
		}
		// hello for문 10번 출력
		int d;
		for(d=0;d<10;d++ ){
			System.out.println("hello for문");
		}
		}
}
		
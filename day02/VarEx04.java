class VarEx04{
	public static void main(String[] args){
		// 카멜표기법 : 단어+단어 뒷단어 첫글자 대문자로 작성
		int maxSpeed;   // 변수 선언
		maxSpeed = 300; // 값 대입
		System.out.println( maxSpeed );
		
		//스네이크 표기법 : 띄어쓰기 사이에 _(언더바)로 작성
		int student_num;
		student_num = 20251028;
		System.out.println( student_num );
		
		// 리터럴 : 직접 코드에서 입력한 값
		int a = 10; // 리터럴O
		int b = a;  // 리터럴X
		System.out.println( a );
		System.out.println( b );
	}
}